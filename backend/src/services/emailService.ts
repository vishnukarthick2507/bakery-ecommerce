import nodemailer from "nodemailer";
import { OTP_EXPIRY_MINUTES } from "./otpService.js";

function getBrevoSmtpConfig() {
  const host = process.env.BREVO_SMTP_HOST;
  const port = parseInt(process.env.BREVO_SMTP_PORT || "587", 10);
  const user = process.env.BREVO_SMTP_USER;
  const pass = process.env.BREVO_SMTP_KEY;
  const from = process.env.BREVO_FROM_EMAIL;
  const fromName = process.env.BREVO_FROM_NAME || "S.V. Sweets & Bakers";

  if (!host || !user || !pass || !from) {
    throw new Error(
      "Brevo SMTP configuration is incomplete. Check BREVO_SMTP_HOST, BREVO_SMTP_USER, BREVO_SMTP_KEY and BREVO_FROM_EMAIL env vars.",
    );
  }

  return { host, port, user, pass, from, fromName };
}

/**
 * Returns true only when all required Brevo SMTP environment variables are set.
 * Used by the controller to distinguish a misconfigured service (503) from a
 * transient delivery failure (502). Never logs credential values.
 */
export function isBrevoSmtpConfigured(): boolean {
  const host = process.env.BREVO_SMTP_HOST;
  const user = process.env.BREVO_SMTP_USER;
  const pass = process.env.BREVO_SMTP_KEY;
  const from = process.env.BREVO_FROM_EMAIL;
  return Boolean(host && user && pass && from);
}

/**
 * Sends a 6-digit OTP to the customer's email address via Brevo SMTP (Nodemailer).
 *
 * @param to - Recipient email address.
 * @param otp - The 6-digit OTP value already generated by the caller.
 * @param purpose - Purpose of the OTP (login / registration / auth / guest checkout).
 * @returns true only when the email was accepted for delivery by the SMTP server.
 *
 * Reads Brevo SMTP credentials exclusively from environment variables.
 * Delivery failures (network, auth, incomplete config) fail closed: false is
 * returned and no OTP session is created by the caller. The OTP value, SMTP
 * credentials, and recipient address are never written to application logs.
 */
export async function sendOtpEmail(
  to: string,
  otp: string,
  purpose: "LOGIN" | "REGISTER" | "AUTH" | "GUEST_CHECKOUT" = "LOGIN",
): Promise<boolean> {
  if (!isBrevoSmtpConfigured()) {
    console.error(
      "OTP email delivery failed: Brevo SMTP is not configured. Set BREVO_SMTP_HOST, BREVO_SMTP_USER, BREVO_SMTP_KEY and BREVO_FROM_EMAIL.",
    );
    return false;
  }

  try {
    const { host, port, user, pass, from, fromName } = getBrevoSmtpConfig();

    const transporter = nodemailer.createTransport({
      host,
      port,
      secure: port === 465,
      auth: {
        user,
        pass,
      },
    });

    const purposeLabel =
      purpose === "LOGIN"
        ? "sign in to your S.V. Sweets & Bakers account"
        : purpose === "REGISTER"
        ? "create your S.V. Sweets & Bakers account"
        : purpose === "GUEST_CHECKOUT"
        ? "confirm your guest checkout"
        : "complete your request";

    const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8">
      <meta name="viewport" content="width=device-width, initial-scale=1.0">
    </head>
    <body style="margin: 0; padding: 0; font-family: 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f3f4f6;">
      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
        <tr>
          <td align="center" style="padding: 20px 0;">
            <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width: 600px;">
              <tr>
                <td align="center" style="padding: 28px 24px; background-color: #7B4B1E; border-radius: 8px 8px 0 0;">
                  <h1 style="color: #ffffff; margin: 0; font-size: 26px; font-weight: bold; letter-spacing: 0.5px;">S.V. Sweets &amp; Bakers</h1>
                  <p style="color: #f3e5d8; margin: 6px 0 0; font-size: 14px;">Freshly Baked. Made With Love.</p>
                </td>
              </tr>
              <tr>
                <td align="center" style="padding: 36px 24px; background-color: #ffffff; border-radius: 0 0 8px 8px;">
                  <h2 style="color: #1f2937; margin: 0 0 12px; font-size: 22px; font-weight: bold;">Your One-Time Password (OTP)</h2>
                  <p style="color: #4b5563; margin: 0 0 26px; font-size: 16px; line-height: 1.5;">
                    Use the code below to ${purposeLabel}.<br>
                    Please do not share this code with anyone.
                  </p>
                  <div style="display: inline-block; padding: 20px 36px; background-color: #7B4B1E; border-radius: 8px; font-size: 36px; font-weight: bold; color: #ffffff; letter-spacing: 10px; font-variant-numeric: tabular-nums;">
                    ${otp}
                  </div>
                  <p style="color: #6b7280; margin: 28px 0 0; font-size: 14px; line-height: 1.5;">
                    This code expires in <strong>${OTP_EXPIRY_MINUTES} minutes</strong>. If you did not request this code, please ignore this email and contact us if you suspect unauthorised access to your account.
                  </p>
                  <hr style="border: none; border-top: 1px solid #e5e7eb; margin: 30px 0;">
                  <p style="color: #9ca3af; font-size: 12px; margin: 0; line-height: 1.5;">
                    S.V. Sweets &amp; Bakers<br>
                    Freshly Baked. Made With Love.<br>
                    This is an automated transactional email. Please do not reply to this message.
                  </p>
                </td>
              </tr>
            </table>
          </td>
        </tr>
      </table>
    </body>
    </html>
  `;

    await transporter.sendMail({
      from: `"${fromName}" <${from}>`,
      to,
      subject: `Your S.V. Sweets & Bakers OTP Code: ${otp}`,
      html,
    });

    return true;
  } catch (error) {
    // Delivery failures fail closed. Log the SMTP failure reason without
    // exposing the OTP, SMTP credentials, or the recipient address.
    const smtpError = error as {
      code?: string;
      responseCode?: number;
      response?: string;
      command?: string;
    };
    const safeDetail =
      smtpError.code || smtpError.responseCode || smtpError.command
        ? `code=${String(
            smtpError.code ?? smtpError.responseCode ?? smtpError.command,
          )}`
        : "";
    console.error(
      `OTP email delivery failed${safeDetail ? ` (${safeDetail})` : ""}: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    return false;
  }
}

/**
 * Diagnostic helper: verifies Brevo SMTP connectivity and authentication.
 *
 * Intended for health-check / startup diagnostics, NOT for the per-request
 * send path (transporter.verify() adds latency on every call).
 *
 * Logs only the outcome and SMTP codes; never credentials, the OTP, or the
 * recipient address.
 */
export async function verifyBrevoSmtpConnection(): Promise<{
  ok: boolean;
  detail?: string;
}> {
  if (!isBrevoSmtpConfigured()) {
    return { ok: false, detail: "Brevo SMTP is not configured" };
  }

  try {
    const { host, port, user, pass } = getBrevoSmtpConfig();
    const transporter = nodemailer.createTransport({
      host,
      port,
      secure: port === 465,
      auth: { user, pass },
    });
    await transporter.verify();
    return { ok: true };
  } catch (error) {
    const smtpError = error as {
      code?: string;
      responseCode?: number;
      command?: string;
    };
    const safeDetail =
      smtpError.code || smtpError.responseCode || smtpError.command
        ? `code=${String(
            smtpError.code ?? smtpError.responseCode ?? smtpError.command,
          )}`
        : "";
    console.error(
      `Brevo SMTP verification failed${safeDetail ? ` (${safeDetail})` : ""}: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    return {
      ok: false,
      detail: error instanceof Error ? error.message : String(error),
    };
  }
}

